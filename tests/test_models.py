@pytest.mark.parametrize("model_name", sorted(MODELS))
def test_a_decision_about_countable_things_is_a_whole_number(model_name):
    """You cannot decide to buy two thirds of a machine.

    Only *decisions* though, and the distinction is worth stating because the first version of
    this test did not make it and failed on a model that was right. A node whose unit is `node`
    is a quantity of machines, and there are perfectly good fractional ones: the average number
    busy at any moment, the point at which a scaling curve turns over. Neither is something
    anybody buys. An input with a count unit is something somebody chose, and 64.3 of them is not
    a choice that can be made.
    """
    model = MODELS[model_name]
    values = point(model, _scenario(model, "reference"))
    for name, node in model.nodes.items():
        if node.kind != "input" or node.unit not in COUNT_UNITS or name not in values:
            continue
        assert values[name] == math.floor(values[name]), (
            f"{model_name}: {name} is {values[name]}, and it is a decision counted in "
            f"{node.unit}s. Somebody has to be able to act on it."
        )


@pytest.mark.parametrize("model_name", sorted(MODELS))
def test_a_sizing_chain_rounds_up_rather_than_to_nearest(model_name):
    """Where a chain lands between two machines, it must land on the larger.

    Rounding to nearest saves half a machine and loses the thing the chain was computing. Every
    derived node in this book that turns a demand into a count of machines says `ceil`, and this
    checks that what comes out of them is whole — so a chain that acquires a division after the
    rounding, which is the way this goes wrong, fails here.
    """
    model = MODELS[model_name]
    values = point(model, _scenario(model, "reference"))
    rounded = [
        name
        for name, node in model.nodes.items()
        if node.kind == "derived" and node.formula_text.strip().startswith("ceil(")
    ]
    for name in rounded:
        assert values[name] == math.floor(values[name]), (
            f"{model_name}: {name} rounds up and is still {values[name]}. Something divides it "
            "after the rounding, which throws the rounding away."
        )


@pytest.mark.parametrize("model_name", sorted(MODELS))
def test_every_ceiling_leaves_room_below_its_limit(model_name):
    model = MODELS[model_name]
    evaluation = evaluate(model, _scenario(model, "reference"))
    for name, report in evaluation.ceilings.items():
        assert isinstance(model.nodes[name], Ceiling)
        assert 0.0 <= report["headroom"] < 1.0, (
            f"{model_name}: {name} declares a headroom of {report['headroom']}, which is either "
            "negative or leaves nothing at all"
        )
        assert report["allowed"] < report["limit"] or report["headroom"] == 0.0
        assert 0.0 <= report["p_over_allowed"] <= 1.0


def test_the_storage_model_accounting_adds_up():
    """The one arithmetic identity worth asserting directly: a total is its parts."""
    model = MODELS["storage_cluster"]
    values = point(model, _scenario(model, "reference"))
    assert values["capex"] == pytest.approx(
        values["drive_capex"] + values["chassis_capex"] + values["network_capex"]
    )
    assert values["tco"] == pytest.approx(values["capex"] + values["lifecycle_opex"])
    assert values["tco"] > values["capex"], "a five-year total that is not above its capital cost"


def test_the_observability_traces_chain_is_blocked_and_says_why():
    """The unmeasured constant propagates, and the reason survives into the stamped result."""
    model = MODELS["observability"]
    blocked = model.blocked()
    assert "spans_per_request" in model.unmeasured
    assert "traces_ingest" in blocked, "the traces chain should be unevaluable"
    assert "spans_per_request" in blocked["traces_ingest"], (
        "a blocked node has to name which missing constant blocked it, or the box on the page "
        "cannot tell the reader what to go and measure"
    )
    assert "metrics_ingest" not in blocked, (
        "only the chain downstream of the missing constant is blocked; the others still compute"
    )


def test_a_scenario_cannot_pin_a_derived_node():
    """Overriding a derived node would make the graph and the number disagree."""
    model = MODELS["storage_cluster"]
    for scenario in scenarios_for(model):
        for name in scenario.overrides:
            assert model.nodes[name].kind != "derived", (
                f"scenario {scenario.name!r} pins {name!r}, which is computed from other nodes"
            )


def test_scenario_files_load_from_disk():
    for model in MODELS.values():
        assert model.path is not None
        for path in sorted((model.path.parent / "scenarios").glob("*.yaml")):
            assert load_scenario(path).samples > 0


