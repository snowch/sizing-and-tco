#: Units that count things somebody buys or provisions.
COUNT_UNITS = ("node", "drive", "core", "host")

MODELS = {model.name: model for model in discover()}


def _scenario(model, name):
    for scenario in scenarios_for(model):
        if scenario.name == name:
            return scenario
    raise AssertionError(f"{model.name} has no scenario {name!r}")


@pytest.mark.parametrize("result_name", sorted(PINS))
def test_the_reference_outputs_are_what_the_book_publishes(result_name):
    model_name, scenario_name = result_name.rsplit("-", 1)
    model = MODELS[model_name]
    evaluation = evaluate(model, _scenario(model, scenario_name))
    for output, (at_point, p5, p95) in PINS[result_name].items():
        assert evaluation.point[output] == pytest.approx(at_point, rel=1e-9), (
            f"{result_name}: {output} at the point estimate moved. If that was deliberate, "
            "re-run `python3 -m bench.run_models` and update the pin in the same commit."
        )
        if p5 is None:
            assert output not in evaluation.summaries
            continue
        assert evaluation.summaries[output]["p5"] == pytest.approx(p5, rel=1e-9)
        assert evaluation.summaries[output]["p95"] == pytest.approx(p95, rel=1e-9)


@pytest.mark.parametrize("result_name", sorted(PINS))
def test_the_stamped_result_agrees_with_a_fresh_run(result_name):
    """The committed file and the code that claims to produce it have not drifted apart."""
    stamped = load_result(result_name)["summary"]
    model_name, scenario_name = result_name.rsplit("-", 1)
    model = MODELS[model_name]
    fresh = evaluate(model, _scenario(model, scenario_name))
    for output in stamped["outputs"]:
        node = stamped["nodes"][output]
        if node.get("blocked_by"):
            assert output not in fresh.point, f"{output} is stamped as blocked but now evaluates"
            continue
        assert fresh.point[output] == pytest.approx(node["point"], rel=1e-9), (
            f"{result_name}: {output} differs from the stamped result. Re-run "
            "`python3 -m bench.run_models`."
        )


