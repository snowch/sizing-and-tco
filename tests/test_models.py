"""The reference scenarios, asserted.

Two layers, and both are needed.

**Pins.** The headline outputs of each reference scenario, written down. They change when the
model, a measured constant or the DSL core changes, and every one of those is a decision somebody
should make deliberately — so a diff that moves them is a diff that has to say why. This is the
sixth of the toolkit's outputs, and it is the one that makes the other five safe to rely on.

**Invariants.** Things that must hold whatever the numbers are: the accounting adds up, a node
count is a whole number, a ceiling's allowed level is below its limit. A pin catches a change; an
invariant catches a class of nonsense, including in a model somebody adds tomorrow.
"""

